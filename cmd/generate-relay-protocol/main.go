// Command generate-relay-protocol emits the RELAY WS protocol types
// (pkg/relay/protocol_types_generated.go, package relay): one Go type per RELAY
// method's params (<Method>Params) and ack result (<Method>Result), from the
// canonical switchblade wire schemas in porting-sdk/combined-specs/relay.yaml,
// read through the shared reader relay_shapes.go (ledger row R11) — the Go port of
// porting-sdk/scripts/relay_protocol_shapes.py. That reader serves (method, node)
// per phase, merging the shapes carried on a registered method
// (methods.<name>.request.params_dto / .response.result) with the six per phase the
// extractor found for methods the vendored spec does not register
// (<phase>_shapes_unattached.methods.<name>) — 64 methods per phase either way.
//
// This replaced a directory of standalone per-method JSON-Schema files
// (relay-protocol/<method>.{params,result}.json, draft-2020-12, extracted from the
// C# switchblade classes). The method name now comes from the document's own key
// rather than from an x-method field with a filename fallback, and the phase from
// the block it was carried in rather than from a filename suffix.
//
// This is the Go realization of the reference generator's generate_relay_protocol
// (porting-sdk/scripts/generate_python_rest_types.py) and the TypeScript
// generateForRelay (signalwire-typescript/scripts/generate-rest-types.ts). It is
// one of the fixed 5 cross-port generator commands (generate_rest,
// generate_rest_tests, generate_relay_protocol, generate_swaig_payloads,
// generate_swml_verbs); the Go realization splits them into separate cmd/ dirs so
// every port exposes the same 5 GEN-FRESH gates.
//
// The declaration follows the same object-vs-alias split as the REST types
// emitter: an object schema WITH properties becomes a Go struct (typed fields,
// json wire-key tags, optional -> *T); an object schema with NO properties (or a
// non-object) becomes a `type X map[string]any` alias — so the three empty-object
// methods (calling.call params/result, signalwire.disconnect result) are aliases,
// NOT surface structs, exactly matching the reference (which emits them as
// `TypeAlias = dict[str, Any]`, keeping the surface at 123 structs).
//
// GEN-FRESH-gated: `--check` reproduces the committed output and exits non-zero
// if the file differs. Resolves porting-sdk via $PORTING_SDK or sibling.
//
// Usage:
//
//	go run ./cmd/generate-relay-protocol          # (re)write protocol_types_generated.go
//	go run ./cmd/generate-relay-protocol --check  # GEN-FRESH: fail if it is stale
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/signalwire/signalwire-go/v3/cmd/internal/gen"
)

// relayHeader is the generated-file banner (names this producing command).
const relayHeader = `// Code generated by cmd/generate-relay-protocol; DO NOT EDIT.
//
// AUTO-GENERATED from porting-sdk/combined-specs/relay.yaml — regenerate with:
//   go run ./cmd/generate-relay-protocol
//
// One Go type per RELAY WS method's params (<Method>Params) and ack result
// (<Method>Result), from the canonical switchblade wire schemas. Object schemas
// with properties become structs (json wire-key tags, optional fields -> *T);
// empty-object / non-object schemas become map[string]any aliases. STATIC-ONLY:
// at runtime each payload is a plain map; this layer just types the shapes.

package relay
`

// relayPhase pairs a phase with the Go type-name suffix.
type relayPhase struct {
	phase  string // "params" / "result"
	suffix string // "Params" / "Result"
}

// emitRelayProtocolFile reads every params/result shape the shared reader serves
// from porting-sdk/combined-specs/relay.yaml and returns the generated
// pkg/relay/protocol_types_generated.go source (gofmt'd by the caller).
//
// It never returns "" for an EMPTY input: a vanished or malformed document is an
// error, not a no-op. The old code returned ("", nil) both when the relay-protocol
// directory did not exist and when it held no schemas, and the caller read that as
// "keep the committed file" — so a deleted input would have silently preserved a
// stale surface and passed. That is the exact failure mode this row exists to
// prevent, so both paths are now loud.
func emitRelayProtocolFile(psdk string) (string, error) {
	var b strings.Builder
	b.WriteString(relayHeader)
	b.WriteString("\n")

	emitted := 0
	// Params block then Result block — each already ordered by method name — to
	// reproduce the reference decl order.
	for _, ph := range []relayPhase{{"params", "Params"}, {"result", "Result"}} {
		shapes, err := relayShapes(psdk, ph.phase)
		if err != nil {
			return "", err
		}
		for _, s := range shapes {
			goName := pascal(strings.ReplaceAll(s.method, ".", "_")) + ph.suffix
			if isObjectSchema(s.node) {
				emitStructDecl(&b, nil, goName, s.node)
			} else {
				fmt.Fprintf(&b, "type %s %s\n\n", goName, goFieldType(nil, s.node))
			}
			emitted++
		}
	}
	if emitted == 0 {
		return "", fmt.Errorf("relay_shapes: %s carried no params/result shapes — refusing to emit an empty RELAY surface", filepath.Join(psdk, combinedRelay))
	}
	return b.String(), nil
}

func run() error {
	check := flag.Bool("check", false, "GEN-FRESH: exit non-zero if the generated file is stale")
	flag.Parse()

	cwd, err := os.Getwd()
	if err != nil {
		return err
	}
	repoRoot, err := gen.FindRepoRoot(cwd)
	if err != nil {
		return err
	}
	// The resolver's MARKER is the input this command actually reads. It used to be
	// the `relay-protocol` DIRECTORY, so once that tree is retired the probe would
	// stop finding an otherwise-perfectly-good porting-sdk and fall into the
	// skip-and-keep-the-committed-file branch below — a vanished input reading as
	// success. Probing the combined document keeps the two in step.
	psdk, err := gen.ResolvePortingSDK(repoRoot, combinedRelay)
	if err != nil {
		if *check {
			return fmt.Errorf("generate-relay-protocol --check: %w", err)
		}
		fmt.Fprintf(os.Stderr, "generate-relay-protocol: %v — skipping (committed files kept)\n", err)
		return nil
	}

	src, err := emitRelayProtocolFile(psdk)
	if err != nil {
		return err
	}
	out := gen.Output{
		Path: filepath.Join(repoRoot, "pkg", "relay", "protocol_types_generated.go"),
		Src:  src,
	}
	return gen.Run(*check, "generate-relay-protocol", "relay protocol", []gen.Output{out})
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		os.Exit(1)
	}
}
